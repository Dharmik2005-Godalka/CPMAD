class Student {
  String name;
  String rollNumber;
  String grNumber;
  String qualification;
  String college;
  List<String> skills;
  String email;
  String phone;
  String location;

  Student({
    required this.name,
    required this.rollNumber,
    required this.grNumber,
    required this.qualification,
    required this.college,
    required this.skills,
    required this.email,
    required this.phone,
    required this.location,
  });
}